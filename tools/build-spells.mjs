/**
 * Builds game/data/spells.js from the Foundry system's spell pack
 * (packs-src/mastery-spells, from Mastery's Spells chapters). Each spell
 * gets the kind of effect the game plays, or `unbuilt` with the reason when
 * its mechanics don't exist yet. Never edit the output.
 *
 *   node tools/build-spells.mjs ../Mastery-Foundry
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(resolve(process.argv[2] || join(here, "..", "..", "Mastery-Foundry")), "mastery", "packs-src", "mastery-spells");
const plain = (html) => String(html || "").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
// Reach in squares (Magic Mastery, Reach): self, touch, Close (30 feet), Distant (100 feet).
const REACH = { self: 0, touch: 1, close: 6, distant: 20 };
// Duration multipliers (Magic Mastery, Duration): instantaneous ×1, short ×3, long ×5, extended ×8.
const DURATION = { instantaneous: 1, short: 3, long: 5, extended: 8 };
// Conditions the game plays, by the name a spell gives.
const CONDS = { Demoralized: "demoralized", Restricted: "restricted", Exhausted: "exhausted", Invigorated: "invigorated", Inspired: "inspired", Tainted: "tainted" };
const MUNDANE_WARD = /mundane/i;

const SPELLS = {};
for (const f of readdirSync(src).sort()) {
  if (f.startsWith("folder")) continue;
  const d = JSON.parse(readFileSync(join(src, f), "utf8"));
  const s = d.system;
  const sp = { form: s.form, command: s.command, cost: s.statedCost ?? null, reach: REACH[s.reach] ?? 6, duration: DURATION[s.duration] || 1,
    concentration: !!s.concentration, noSomatic: s.components?.somatic === false, text: plain(s.description) };
  const resist = /^(\w+)/.exec(s.resistance || "")?.[1]?.toLowerCase();
  const enemyTrial = resist && !/^N\/A/.test(s.resistance);
  const cond = /^(\w+) T(\d)/.exec(s.conditionText || "");
  const effect = s.effectText || "";
  if (sp.cost == null) sp.unbuilt = "its cost varies with what it restores";
  else if (s.command === "obliterate" && /ATD \+ MD/.test(s.damage) && enemyTrial) {
    sp.kind = s.scale === "personal" ? "damage" : "area"; sp.type = s.form; sp.resist = resist;
    if (sp.kind === "area") sp.area = 1; // Large: up to 3×3 squares, a square out from the center
  } else if (s.command === "enchant" && /\(aura\)/.test(s.damage)) {
    sp.kind = "aura"; sp.type = s.form; // a contact aura of the form's mastery level
  } else if (s.command === "enchant" && cond && CONDS[cond[1]]) {
    sp.cond = CONDS[cond[1]];
    sp.kind = enemyTrial ? "condition" : "buff";
    if (enemyTrial) sp.resist = resist;
  } else if (s.command === "preservate" && /Protection vs (\w+)/.test(effect)) {
    sp.kind = "ward"; sp.against = MUNDANE_WARD.test(effect) ? "mundane" : /Protection vs (\w+)/.exec(effect)[1];
  } else if (s.command === "transmute" && /^Healing/.test(effect)) sp.kind = "heal";
  else if (s.command === "transmute" && /Reduce Tainted/.test(effect)) { sp.kind = "cleanse"; sp.cond = "tainted"; }
  else sp.unbuilt = cond ? `${cond[1]} isn't in the game yet` : s.command === "transmute" && /Trauma|Insanity/.test(effect) ? "restoring Traumas isn't built yet"
    : { divine: "divination isn't built yet", formulate: "barriers and constructs aren't built yet", evoke: "summoning isn't built yet" }[s.command] || `${effect || "its effect"} isn't built yet`;
  if (s.reach === "self") sp.self = true;
  if (s.reach === "touch") sp.touch = true;
  SPELLS[d.name] = sp;
}
const body = `/**\n * GENERATED by tools/build-spells.mjs from the Foundry spell pack. Do not edit.\n * reach: squares (0 self, 1 touch, 6 Close, 20 Distant); duration: the multiplier.\n */\nexport const SPELLS = ${JSON.stringify(SPELLS, null, 1)};\n\n/** Damage age multipliers for healing (Magic Mastery, Healing and Repair). */\nexport const DAMAGE_AGE = { round: 1, encounter: 3, half: 5, previous: 8 };\n\nconst MUNDANE = ["cutting", "cleaving", "crushing", "piercing", "puncturing"];\nexport const wardCovers = (against, type) => against === type || (against === "mundane" && MUNDANE.includes(type));\n`;
writeFileSync(join(here, "..", "game", "data", "spells.js"), body);
const built = Object.values(SPELLS).filter(x => !x.unbuilt).length;
console.log(`${Object.keys(SPELLS).length} spells, ${built} playable`);
