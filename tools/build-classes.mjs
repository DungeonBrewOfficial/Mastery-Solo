/**
 * Builds game/data/classes.js from the Foundry system's class pack
 * (packs-src/mastery-classes), which is itself generated from Mastery Core
 * Classes. Keeps the advancement data only; never edit the output.
 *
 *   node tools/build-classes.mjs ../Mastery-Foundry
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(process.argv[2] || join(here, "..", "..", "Mastery-Foundry"), "mastery");
const src = join(root, "packs-src", "mastery-classes");
const { CLASS_XP } = await import(join(root, "module", "data", "chargen-data.mjs"));
const plain = (html) => String(html || "").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

// Class features (hallmarks), by id, for the names on a sheet.
const hallmarks = {};
for (const f of readdirSync(src)) if (f.startsWith("hallmark-")) { const d = JSON.parse(readFileSync(join(src, f), "utf8")); hallmarks[d._id] = d.name; }

const out = {};
for (const f of readdirSync(src).sort()) {
  if (!f.startsWith("class-")) continue;
  const d = JSON.parse(readFileSync(join(src, f), "utf8"));
  const s = d.system;
  const keys = (o, v) => Object.entries(o || {}).filter(([, x]) => x === v).map(([k]) => k);
  out[d.name] = {
    name: d.name,
    xp: CLASS_XP[d.name] || null,
    progression: { weapon: s.weaponProgression || null, spell: s.spellProgression || null, skill: s.skillProgression || null },
    weaponCap: s.weaponMasteryCap || null,
    freeStyle: /invest one point for free into a single Combat Style/i.test(plain(s.investmentRules)),
    skills: { learnable: keys(s.skillAccess, "learnable"), free: keys(s.skillAccess, "free"), barred: keys(s.skillAccess, "barred") },
    trade: { learnable: keys(s.tradeDisciplineAccess, "learnable"), barred: keys(s.tradeDisciplineAccess, "barred") },
    forms: keys(s.magicFormAccess, "learnable"),
    freeSkillAt: (s.freeSkillProgression || []).map(x => ({ level: x.level, tier: x.tier })),
    titles: s.titleTable || [],
    healthPer3Levels: s.healthPer3Levels || 0,
    castingAttribute: s.castingAttribute || null,
    hallmarks: [...new Set((s.hallmarkUuids || []).map(u => hallmarks[u.split(".").pop()]).filter(Boolean))],
    equipment: s.equipmentRestrictions || null
  };
}
const body = `/**\n * GENERATED by tools/build-classes.mjs from the Foundry class pack. Do not edit.\n */\nexport const CLASSES = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(join(here, "..", "game", "data", "classes.js"), body);
console.log(`${Object.keys(out).length} classes`);
