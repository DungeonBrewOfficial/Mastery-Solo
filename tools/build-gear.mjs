/**
 * Builds game/data/gear.js from the Foundry system's gear pack
 * (packs-src/mastery-gear), which is itself generated from Mastery's
 * equipment chapters. Keeps only what the game needs; never edit the output.
 *
 *   node tools/build-gear.mjs ../Mastery-Foundry
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(resolve(process.argv[2] || join(here, "..", "..", "Mastery-Foundry")), "mastery", "packs-src", "mastery-gear");
// Coin values in silver pennies (Equipment, Coinage).
const SP = { cf: 0.25, sh: 0.5, sp: 1, ep: 2, sg: 4, st: 6, ss: 12, sf: 24, sc: 60, gn: 80, gm: 160, gs: 240 };

const out = {};
const skipped = [];
for (const f of readdirSync(src).sort()) {
  let d;
  try { d = JSON.parse(readFileSync(join(src, f), "utf8")); } catch { skipped.push(f); continue; }
  if (!d.system) continue; // folders
  const s = d.system;
  const cost = s.cost ? Math.round((s.cost.value || 0) * (SP[s.cost.currency] ?? 1) * 4) / 4 : 0;
  const item = { name: d.name, kind: d.type === "kit" ? "kit" : d.type === "container" ? "container" : s.category || "gear", sp: cost };
  if (s.weather?.slot) item.weather = { slot: s.weather.slot, tags: s.weather.tags || [] };
  if (s.stack > 1) item.stack = s.stack;
  if (s.weightLbs) item.lbs = s.weightLbs;
  if (d.type === "kit") item.contents = (s.contents || []).map(c => ({ name: c.name, qty: c.qty || 1 }));
  out[d.name] = item;
}
// A kit's price is the sum of what it holds when the pack gives none.
for (const k of Object.values(out)) if (k.kind === "kit" && !k.sp) k.sp = k.contents.reduce((n, c) => n + (out[c.name]?.sp || 0) * c.qty, 0);
const body = `/**\n * GENERATED by tools/build-gear.mjs from the Foundry gear pack. Do not edit.\n * Prices are in silver pennies (a copper farthing is 0.25).\n */\nexport const GEAR = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(join(here, "..", "game", "data", "gear.js"), body);
console.log(`${Object.keys(out).length} items${skipped.length ? `; skipped unreadable ${skipped.join(", ")}` : ""}`);
