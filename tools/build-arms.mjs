/**
 * Builds game/data/arms.js from the Foundry system's weapon, armor, and
 * shield packs (from Mastery's Equipment chapters): weapons in the shape the
 * party's sheets use, armor sets with their summed Durability and
 * resistance, and shields. Never edit the output.
 *
 *   node tools/build-arms.mjs ../Mastery-Foundry
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(process.argv[2] || join(here, "..", "..", "Mastery-Foundry"), "mastery");
const { MASTERY } = await import(join(root, "module", "config.mjs"));
const pack = (name) => readdirSync(join(root, "packs-src", name)).map(f => { try { return JSON.parse(readFileSync(join(root, "packs-src", name, f), "utf8")); } catch { return null; } }).filter(d => d?.system);
const SP = { cf: 0.25, sh: 0.5, sp: 1, ep: 2, sg: 4, st: 6, ss: 12, sf: 24, sc: 60, gn: 80, gm: 160, gs: 240 };
const price = (c) => c ? Math.round((c.value || 0) * (SP[c.currency] ?? 1) * 4) / 4 : 0;
const LABEL = { lightProjectile: "Light Projectile", heavyProjectile: "Heavy Projectile", crossbow: "Crossbow", lightThrown: "Light Thrown", heavyThrown: "Heavy Thrown",
  lightOneHanded: "Light One-Handed", heavyOneHanded: "Heavy One-Handed", versatileOneHanded: "Versatile One-Handed", versatileTwoHanded: "Versatile Two-Handed", twoHanded: "Two-Handed" };

const WEAPONS = {};
for (const d of pack("mastery-weapons")) {
  const s = d.system;
  if (!s.category || s.category === "crossbow") continue; // crossbows roll fixed dice; not carried by recruits yet
  const cat = MASTERY.weaponCategories[s.category];
  const r = s.rangeIncrements || {};
  const launcher = s.launcherKind || "";
  const w = { name: d.name, category: LABEL[s.category], track: s.damageTrackOverride || cat.track, speed: s.speedOverride || cat.speed,
    attribute: s.attributeOverride || cat.attr, type: s.weaponType, damage: s.damageTypes?.[0] || (launcher === "sling" ? "crushing" : "piercing"), sp: price(s.cost) };
  if (["twoHanded", "versatileTwoHanded"].includes(s.category)) w.twoHanded = true;
  if (cat.ranged || (r.far && !launcher)) {
    if (cat.ranged) w.ranged = true;
    if (r.far) w.range = [r.short / 5, r.moderate / 5, r.far / 5];
    if (launcher) w.projectile = true;
    else if (cat.ranged) { w.thrown = true; w.count = s.stack > 1 ? s.stack : 1; }
  }
  const def = (s.properties || []).map(p => /^\+(\d) to Defense$/.exec(p.name)).find(Boolean);
  if (def) w.defense = Number(def[1]);
  WEAPONS[d.name] = w;
}

const pieces = Object.fromEntries(pack("mastery-armor").map(d => [d.name, d.system]));
const ARMOR = {};
for (const d of pack("mastery-armor")) {
  const s = d.system;
  if (!d.name.startsWith("(Set) ") || s.barding || /Barding/.test(d.name)) continue;
  const parts = (s.pieces || []).map(p => pieces[p.name]).filter(Boolean);
  const resistance = {};
  for (const p of parts) for (const [k, v] of Object.entries(p.resistance || {})) resistance[k] = (resistance[k] || 0) + v;
  const name = d.name.replace("(Set) ", "");
  ARMOR[name] = { name, weightClass: s.weightClass, durability: parts.reduce((n, p) => n + (p.durabilityMax || 0), 0), resistance, sp: price(s.cost) };
}
const SHIELDS = {};
for (const d of pack("mastery-shields")) {
  const s = d.system;
  if (s.deployable || d.name === "Pavise") continue;
  SHIELDS[d.name] = { name: d.name, defense: s.defenseBonus, durability: s.durabilityMax, sp: price(s.cost) };
}

const body = `/**\n * GENERATED by tools/build-arms.mjs from the Foundry weapon, armor, and shield packs. Do not edit.\n * Prices in silver pennies; ranges in squares (feet ÷ 5); armor resistance before the wearer's Agility.\n */\nexport const WEAPONS = ${JSON.stringify(WEAPONS, null, 1)};\nexport const ARMOR = ${JSON.stringify(ARMOR, null, 1)};\nexport const SHIELDS = ${JSON.stringify(SHIELDS, null, 1)};\n`;
writeFileSync(join(here, "..", "game", "data", "arms.js"), body);
console.log(`${Object.keys(WEAPONS).length} weapons, ${Object.keys(ARMOR).length} armor sets, ${Object.keys(SHIELDS).length} shields`);
